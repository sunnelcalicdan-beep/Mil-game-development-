const clients =
    new Set();

function broadcastLibraryUpdate() {

    const payload = {
        timestamp:
            Date.now()
    };

    const message =
        "event: library-update\n" +
        "data: " +
        JSON.stringify(payload) +
        "\n\n";

    for (
        const client of clients
    ) {

        try {

            client.write(
                message
            );

        }

        catch {

            clients.delete(
                client
            );
        }
    }
}

