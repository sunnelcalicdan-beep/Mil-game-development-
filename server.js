/*
========================================================
USERNAME CLEANING
========================================================

Example:

John Doe
    ->
John-Doe

John_123
    ->
John-123
========================================================
*/

function cleanUsernameForKey(
    username
) {

    let value =
        String(username || "")
            .trim();

    value =
        value.replace(
            /[^a-zA-Z0-9_-]+/g,
            "-"
        );

    value =
        value.replace(
            /[-_]+/g,
            "-"
        );

    value =
        value.replace(
            /^-+|-+$/g,
            ""
        );

    if (!value) {
        value = "User";
    }

    return value.slice(
        0,
        40
    );
}

/*
========================================================
RANDOM KEY CODE
========================================================

Ambiguous characters are excluded:

0
O
I
1
========================================================
*/

function generateRandomCode(
    length = 8
) {

    const alphabet =
        "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

    let code = "";

    while (
        code.length < length
    ) {

        const byte =
            crypto.randomBytes(1)[0];

        const index =
            byte % alphabet.length;

        code +=
            alphabet[index];
    }

    return code;
}

